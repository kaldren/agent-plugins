#!/usr/bin/env python3
"""Convert a Claude Code agent (.md with frontmatter) into a Codex custom agent (.toml).

Claude:  agents/<name>.md      frontmatter (name, description, tools, model, ...) + body = prompt
Codex:   ~/.codex/agents/<name>.toml   name, description, developer_instructions [, model]

Claude-only fields (tools, model, color, ...) are dropped: Claude model names and tool
names don't exist in Codex. Set `codex-model:` in the frontmatter to pin a Codex model.

Usage: agent_md_to_toml.py <agent.md>   (writes the TOML to stdout)
"""

import json
import sys
from pathlib import Path

MARKER = "# generated by agent-plugins from {source}; edit the .md, not this file"


def parse(text):
    """Split frontmatter (simple `key: value` lines) from the body."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError("missing frontmatter (file must start with ---)")
    try:
        end = next(i for i, line in enumerate(lines[1:], 1) if line.strip() == "---")
    except StopIteration:
        raise ValueError("frontmatter is not closed with ---") from None

    meta = {}
    for line in lines[1:end]:
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        key, sep, value = line.partition(":")
        if not sep:
            raise ValueError(f"unsupported frontmatter line: {line!r}")
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        meta[key.strip()] = value

    body = "\n".join(lines[end + 1 :]).strip() + "\n"
    return meta, body


def toml_string(value):
    # A JSON string is also a valid TOML basic string.
    return json.dumps(value, ensure_ascii=False)


def convert(path):
    meta, body = parse(path.read_text(encoding="utf-8"))
    for field in ("name", "description"):
        if not meta.get(field):
            raise ValueError(f"frontmatter needs a non-empty `{field}`")

    out = [MARKER.format(source=path.as_posix())]
    out.append(f"name = {toml_string(meta['name'])}")
    out.append(f"description = {toml_string(meta['description'])}")
    if meta.get("codex-model"):
        out.append(f"model = {toml_string(meta['codex-model'])}")
    out.append(f"developer_instructions = {toml_string(body)}")
    return "\n".join(out) + "\n"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__.strip().splitlines()[-1])
    path = Path(sys.argv[1])
    try:
        sys.stdout.write(convert(path))
    except ValueError as e:
        sys.exit(f"{path}: {e}")


if __name__ == "__main__":
    main()
